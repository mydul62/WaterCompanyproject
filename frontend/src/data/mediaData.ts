export function getStoryBySlug(slug: string): PressStory | undefined {
  const query = decodeURIComponent(slug).toLowerCase();
  return (
    PRESS_STORIES.find(
      (s) => s.slug.toLowerCase() === query || s.id.toLowerCase() === query
    ) || PRESS_STORIES[0]
  );
}

